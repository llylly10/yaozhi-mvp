def score_text(text: str, w_strong: int, w_weak: int):
    """对一段文本计分：strong 词 ×w_strong，weak 词 ×w_weak。"""
    scores = {}
    for ch, kw in CHAPTER_KEYWORDS.items():
        s = 0
        for w in kw["strong"]:
            if w in text:
                s += w_strong
        for w in kw["weak"]:
            if w in text:
                s += w_weak
        if s:
            scores[ch] = s
    return scores


def map_question(q):
    """三档判定：题干强命中≥2 → 权威；题干单章弱命中=1 → 映射；题干无信号 → 选项信号≥2。"""
    stem_sc = score_text(q.stem, 2, 1)
    opt_sc = score_text("".join(o["text"] for o in (q.options or [])), 1, 0)
    total = {ch: stem_sc.get(ch, 0) + opt_sc.get(ch, 0) for ch in set(stem_sc) | set(opt_sc)}

    ranked_stem = sorted(stem_sc.items(), key=lambda kv: -kv[1])
    if ranked_stem:
        top, top_s = ranked_stem[0]
        if top_s >= 2:  # 题干 strong 命中，权威
            ties = [ch for ch, s in ranked_stem if s == top_s and ch != top]
            if ties:
                cands = sorted([top] + ties)
                return ",".join(f"CH{c}" for c in cands), top_s, f"题干并列 {cands}"
            return f"CH{top}", top_s, "题干命中"
        if len(stem_sc) == 1:  # 题干单章弱命中（如"药物的副作用是指"）
            return f"CH{top}", top_s, "题干弱命中"
        # 题干弱且多章竞争 → 落入总分判定

    ranked = sorted(total.items(), key=lambda kv: -kv[1])
    if not ranked or ranked[0][1] < THRESHOLD:
        return "", 0, ""
    top, top_s = ranked[0]
    ties = [ch for ch, s in ranked if s == top_s and ch != top]
    if ties:
        cands = sorted([top] + ties)
        return ",".join(f"CH{c}" for c in cands), top_s, f"选项并列 {cands}"
    return f"CH{top}", top_s, f"选项信号 {top_s}分"


def main():
    apply = "--apply" in sys.argv
    db = SessionLocal()
    try:
        rows = db.query(TikuQuestion).all()
        stats = {}          # ch -> 题数
        unmapped = []
        multi = []
        examples = {}
        for q in rows:
            ref, score, note = map_question(q)
            if not ref:
                unmapped.append((q.paper_no, q.qid, q.stem[:40]))
                continue
            if "," in ref:
                multi.append((q.paper_no, q.qid, ref, q.stem[:40]))
            first = ref.split(",")[0]
            stats[first] = stats.get(first, 0) + 1
            examples.setdefault(first, []).append((q.paper_no, q.qid, q.stem[:36], score))
            if apply:
                q.chapter_ref = ref
        if apply:
            db.commit()
            print("已写库 ✓")
        print(f"映射覆盖: {sum(stats.values())}/{len(rows)} 题")
        print(f"并列映射: {len(multi)} 题")
        print("\n章节分布:")
        for ch in sorted(int(k[2:]) for k in stats):
            print(f"  CH{ch:>2} {stats[f'CH{ch}']:>3} 题")
        print(f"\n未映射 {len(unmapped)} 题（前 30）:")
        for p, qid, stem in unmapped[:30]:
            print(f"  {p}-{qid}: {stem}")
        print(f"\n并列映射 {len(multi)} 题（前 15）:")
        for p, qid, ref, stem in multi[:15]:
            print(f"  {p}-{qid} -> {ref}: {stem}")
        print("\n抽样（每章前 1 题）:")
        for ch in sorted(int(k[2:]) for k in stats):
            tag = f"CH{ch}"
            p, qid, stem, score = examples[tag][0]
            print(f"  {tag}: {p}-{qid} [{score}分] {stem}")
    finally:
        db.close()


if __name__ == "__main__":
    main()
