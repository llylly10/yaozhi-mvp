def get_clinical_cases_summary() -> list[dict[str, Any]]:
    """返回案例列表概览（不含答案与解析，供学生端选择练习）。"""
    summaries = []
    for c in CLINICAL_CASES:
        summaries.append({
            "id": c["id"],
            "title": c["title"],
            "category": c["category"],
            "patient_gender": c["patient"]["gender"],
            "patient_age": c["patient"]["age"],
            "chief_complaint": c["patient"]["chief_complaint"],
            "questions_count": len(c["questions"]),
            "drugs_count": len(c["patient"]["current_prescription"])
        })
    return summaries


def get_clinical_case_detail(case_id: str) -> dict[str, Any] | None:
    """返回单个案例题目详情（抹去正确答案与解析，由前端作答）。"""
    for c in CLINICAL_CASES:
        if c["id"] == case_id:
            return {
                "id": c["id"],
                "title": c["title"],
                "category": c["category"],
                "patient": c["patient"],
                "questions": [
                    {
                        "qid": q["qid"],
                        "stem": q["stem"],
                        "options": q["options"]
                    }
                    for q in c["questions"]
                ]
            }
    return None


def evaluate_clinical_case(case_id: str, answers: dict[str, str]) -> dict[str, Any] | None:
    """判分并返回全套临床药理分析链条、指南依据与教材出处。"""
    case = next((c for c in CLINICAL_CASES if c["id"] == case_id), None)
    if not case:
        return None

    results = []
    correct_cnt = 0
    total_cnt = len(case["questions"])

    for q in case["questions"]:
        qid = q["qid"]
        user_ans = (answers.get(qid) or "").strip().upper()
        is_corr = (user_ans == q["answer"])
        if is_corr:
            correct_cnt += 1
        results.append({
            "qid": qid,
            "stem": q["stem"],
            "options": q["options"],
            "user_answer": user_ans,
            "correct_answer": q["answer"],
            "is_correct": is_corr,
            "analysis": q["analysis"]
        })

    score_ratio = round(correct_cnt / total_cnt, 2) if total_cnt > 0 else 0.0
    score_pct = int(round(score_ratio * 100))
    passed = score_pct >= 60
    star_rating = 3 if correct_cnt == total_cnt else (2 if score_pct >= 60 else (1 if correct_cnt > 0 else 0))

    return {
        "case_id": case_id,
        "title": case["title"],
        "category": case["category"],
        "total_questions": total_cnt,
        "correct_count": correct_cnt,
        "score": score_pct,
        "score_ratio": score_ratio,
        "passed": passed,
        "star_rating": star_rating,
        "results": results,
        "evaluations": {r["qid"]: r for r in results},
        "pharmacist_summary": case["pharmacist_summary"],
        "textbook_reference": case["textbook_reference"]
    }
